import { createSerializationAdapter } from '@tanstack/react-router'

// Payload documents are plain JSON at runtime but carry internal `_transforms` maps
// that fail TanStack Start's strict serializability typing. The test stays narrow so it
// only claims stored documents — never React elements or router/RSC internals.
export const payloadDocAdapter = createSerializationAdapter({
  key: 'payload-document',
  test: (value): value is object =>
    typeof value === 'object' &&
    value !== null &&
    !('$$typeof' in value) &&
    'id' in value &&
    ('createdAt' in value || 'updatedAt' in value),
  toSerializable: (value) => value,
  fromSerializable: (value) => value,
})

// TanStack Start reads registered adapters from `Register['config']`, normally
// generated by the Start plugin; declare it here so plain `tsc` agrees.
declare module '@tanstack/router-core' {
  interface Register {
    config: {
      '~types': {
        serializationAdapters: [typeof payloadDocAdapter]
      }
    }
  }
}
